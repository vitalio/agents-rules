#!/usr/bin/env python3
"""Usage:
  python3 build.py            Build standalone ./agents_rules from src/
  python3 build.py --check    Verify that ./agents_rules is up to date with src/
  python3 build.py -h|--help  Print this usage and exit 0
"""
from __future__ import annotations

if __doc__ is None:
    raise SystemExit("missing usage documentation")

import ast
import pprint
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC_DIR = ROOT / "src"
OUT_FILE = ROOT / "agents_rules"

RULE_ORDER = [
    "core/start",
    "core/secrets",
    "core/plan",
    "core/edit",
    "core/diff-review",
    "core/external",
    "core/end",
    "core/lang",
    "core/unix-philosophy",
    "vcs/git",
    "vcs/cvs",
    "release/semver",
    "release/single-file-build",
    "stack/python-cli",
]

PRESET_ORDER = ["core", "workflow", "default", "python-tool"]


def load_embedded_assets() -> str:
    rules_root = SRC_DIR / "rules"
    rule_files = {
        p.relative_to(rules_root).with_suffix("").as_posix(): p
        for p in sorted(rules_root.rglob("*.md"))
    }
    ordered_rules = [k for k in RULE_ORDER if k in rule_files] + [
        k for k in sorted(rule_files) if k not in RULE_ORDER
    ]
    rules: dict[str, tuple[str, str]] = {}
    for name in ordered_rules:
        raw = rule_files[name].read_text(encoding="utf-8").splitlines()
        desc = name
        body_lines = raw
        if raw and raw[0].startswith("# Description:"):
            desc = raw[0].split(":", 1)[1].strip()
            body_lines = raw[1:]
        rules[name] = (desc, "\n".join(body_lines).strip())

    presets_root = SRC_DIR / "presets"
    preset_files = {
        p.relative_to(presets_root).with_suffix("").as_posix(): p
        for p in sorted(presets_root.rglob("*.preset"))
    }
    ordered_presets = [k for k in PRESET_ORDER if k in preset_files] + [
        k for k in sorted(preset_files) if k not in PRESET_ORDER
    ]
    presets: dict[str, tuple[str, list[str], dict[str, str]]] = {}
    for name in ordered_presets:
        desc = name
        inc: list[str] = []
        p_vars: dict[str, str] = {}
        for raw_line in preset_files[name].read_text(encoding="utf-8").splitlines():
            line = raw_line.strip()
            if not line:
                continue
            if line.startswith("# Description:"):
                desc = line.split(":", 1)[1].strip()
                continue
            if line.startswith("#") or line.startswith(";"):
                continue
            if "=" in line:
                k, v = line.split("=", 1)
                key, val = k.strip(), v.strip()
                if key.lower() == "include":
                    inc.extend(x.strip() for x in val.split(",") if x.strip())
                elif re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
                    p_vars[key] = val
        presets[name] = (desc, inc, p_vars)

    lines = [
        "# --- Embedded std rules and presets (generated by build.py from src/) ---",
        f"EMBEDDED_RULES: dict[str, tuple[str, str]] = {pprint.pformat(rules, width=100, sort_dicts=False)}",
        "",
        f"EMBEDDED_PRESETS: dict[str, tuple[str, list[str], dict[str, str]]] = {pprint.pformat(presets, width=100, sort_dicts=False)}",
        "",
    ]
    return "\n".join(lines)


def assemble_source() -> str:
    chunks = [
        (SRC_DIR / "header.py").read_text(encoding="utf-8").rstrip(),
        load_embedded_assets().rstrip(),
        (SRC_DIR / "engine.py").read_text(encoding="utf-8").rstrip(),
        (SRC_DIR / "cli.py").read_text(encoding="utf-8").rstrip(),
    ]
    source = "\n\n\n".join(chunks) + "\n"
    ast.parse(source)
    return source


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "-h" in args or "--help" in args:
        sys.stdout.write(__doc__)
        return 0
    expected = assemble_source()
    if "--check" in args:
        if not OUT_FILE.is_file() or OUT_FILE.read_text(encoding="utf-8") != expected:
            sys.stderr.write("build.py: agents_rules is out of sync with src/ (run 'python3 build.py')\n")
            return 1
        return 0
    if args:
        sys.stderr.write(__doc__)
        return 2
    OUT_FILE.write_text(expected, encoding="utf-8")
    OUT_FILE.chmod(0o755)
    sys.stdout.write(f"build.py: built {OUT_FILE} ({len(expected.splitlines())} lines)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
